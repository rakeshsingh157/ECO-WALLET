import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../providers/locale_provider.dart';

extension LocalizationExtension on BuildContext {
  String tr(String key) {
    return watch<LocaleProvider>().tr(key);
  }

  String trRead(String key) {
    return read<LocaleProvider>().tr(key);
  }

  String trCategory(String category) {
    switch (category.toLowerCase().trim()) {
      case 'all':
        return tr('all_categories');
      case 'groceries':
        return tr('groceries');
      case 'beverages':
        return tr('beverages');
      case 'snacks':
        return tr('snacks');
      case 'grains':
        return tr('grains');
      case 'spices':
        return tr('spices');
      case 'bakery':
        return tr('bakery');
      case 'oil & ghee':
      case 'oil_ghee':
        return tr('oil_ghee');
      case 'dairy':
        return tr('dairy');
      case 'personal care':
      case 'personal_care':
        return tr('personal_care');
      case 'general':
        return tr('general');
      case 'cleaning':
        return tr('cleaning');
      default:
        return category;
    }
  }

  String trExpenseCategory(String category) {
    switch (category.toLowerCase().trim()) {
      case 'all':
        return tr('all_categories');
      case 'utilities':
        return tr('utilities');
      case 'rent':
        return tr('rent');
      case 'staff & salary':
      case 'staff_salary':
        return tr('staff_salary');
      case 'transport':
        return tr('transport');
      case 'tea & snacks':
      case 'tea_snacks':
        return tr('tea_snacks');
      case 'maintenance':
        return tr('maintenance');
      case 'other':
        return tr('other');
      default:
        return category;
    }
  }

  String trRole(String role) {
    switch (role.toLowerCase().trim()) {
      case 'counter cashier':
      case 'cashier':
        return tr('counter_cashier');
      case 'store manager':
      case 'manager':
        return tr('store_manager');
      default:
        return role;
    }
  }

  String trReturnReason(String reason) {
    switch (reason.toLowerCase().trim()) {
      case 'customer changed mind':
        return tr('reason_customer_mind');
      case 'defective / damaged':
      case 'defective':
        return tr('reason_defective');
      case 'expired product':
      case 'expired':
        return tr('reason_expired');
      case 'wrong item billed':
      case 'wrong item':
        return tr('reason_wrong_item');
      case 'price issue':
        return tr('reason_price_issue');
      case 'other':
        return tr('other');
      default:
        return reason;
    }
  }
}

